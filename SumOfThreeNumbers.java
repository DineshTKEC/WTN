public class SumOfThreeNumbers {
    public static void main(String[] args) {
        // Declare and initialize three numbers
        int num1 = 10;
        int num2 = 20;
        int num3 = 30;
        
        // Calculate the sum
        int sum = num1 + num2 + num3;
        
        // Display the result
        System.out.println("The sum of " + num1 + ", " + num2 + ", and " + num3 + " is: " + sum);
    }
}